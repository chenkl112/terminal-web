import { test, expect } from '@playwright/test';

test('all history filters across workspaces, connected state is green and composer caption is removed', async ({ page, request }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.connection-info')).toHaveClass(/is-connected/);
  await expect(page.locator('.connection-info')).toHaveCSS('color', 'rgb(74, 222, 128)');
  await expect(page.locator('.connection-light')).toHaveCSS('background-color', 'rgb(74, 222, 128)');
  await expect(page.getByText('文件先保存在本机，发送后交给 Codex 处理', { exact: false })).toHaveCount(0);
  await page.getByRole('button', { name: '全部历史', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '全部历史会话' });
  await expect(dialog.locator('.history-list')).toHaveAttribute('aria-busy', 'false');
  const all = await (await request.get('/api/history')).json();
  await expect(dialog.locator('.history-filters>span')).toHaveText(`${all.total} 个会话`);
  await expect(dialog.getByRole('combobox', { name: '历史会话工作区' })).toHaveValue('');
  const cwd = all.workspaces[0];
  await dialog.getByRole('combobox', { name: '历史会话工作区' }).selectOption(cwd);
  await expect(dialog.locator('.history-list')).toHaveAttribute('aria-busy', 'false');
  for (const text of await dialog.locator('.history-row-content>small>span').allTextContents()) expect(text).toBe(cwd);
  await dialog.getByRole('combobox', { name: '历史会话状态' }).selectOption('true');
  await expect(dialog.locator('.history-list')).toHaveAttribute('aria-busy', 'false');
  for (const row of await dialog.locator('.history-row').all()) await expect(row).toContainText('已归档');
  await dialog.getByRole('textbox', { name: '搜索全部历史' }).fill('不存在的会话_TEST_HISTORY_024');
  await expect(dialog.getByText('没有匹配的会话')).toBeVisible();
  await page.keyboard.press('Escape'); await expect(dialog).not.toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  if (!(await page.getByRole('button', { name: '全部历史', exact: true }).isVisible())) await page.getByRole('button', { name: '展开侧栏' }).click();
  await page.getByRole('button', { name: '全部历史', exact: true }).click();
  await expect(dialog.locator('.history-list')).toHaveAttribute('aria-busy', 'false');
  const bounds = await dialog.boundingBox();
  expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x + bounds.width).toBeLessThanOrEqual(390);
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBeTruthy();
  await page.screenshot({ path: '.data/history-mobile.png' });
  expect(errors).toEqual([]);
});

test('real native conversation opens its full saved messages without sending a turn', async ({ page, request }) => {
  test.skip(!process.env.LIVE_HISTORY_TITLE, 'Set LIVE_HISTORY_TITLE to a saved conversation for read-only verification');
  const title = process.env.LIVE_HISTORY_TITLE;
  const list = await (await request.get(`/api/history?q=${encodeURIComponent(title)}`)).json();
  const target = list.items.find(item => item.title === title && item.source === 'codex');
  expect(target).toBeTruthy();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: '全部历史', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '全部历史会话' });
  await dialog.getByRole('textbox', { name: '搜索全部历史' }).fill(title);
  await expect(dialog.locator('.history-row')).toHaveCount(1);
  await dialog.locator('.history-row').click();
  await expect(dialog).not.toBeVisible();
  await expect.poll(() => page.evaluate(() => localStorage.getItem('mono-active-chat'))).toBe(target.key);
  const state = await (await request.get('/api/state')).json();
  const imported = state.conversations.find(item => item.id === target.key);
  expect(imported.nativeHistory).toBe(true); expect(imported.cwd).toBe(target.cwd); expect(imported.turns.length).toBeGreaterThan(0);
  const items = imported.turns.flatMap(turn => turn.items);
  await expect(page.locator('.user-message')).toHaveCount(items.filter(item => item.type === 'userMessage').length);
  await expect(page.locator('.agent-message')).toHaveCount(items.filter(item => item.type === 'agentMessage').length);
  expect(items.some(item => item.type === 'agentMessage' && item.text.length > 0)).toBeTruthy();
  const count = await page.locator('.agent-message').count();
  await page.reload(); await expect(page.locator('.agent-message')).toHaveCount(count);
  await page.screenshot({ path: '.data/history-native-desktop.png' });
  expect(errors).toEqual([]);
});
